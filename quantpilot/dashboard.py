"""Local Streamlit research dashboard; no order controls are exposed."""
from __future__ import annotations

import streamlit as st

from quantpilot.backtest import run_backtest
from quantpilot.config import Settings
from quantpilot.exchange.binance import BinanceFuturesClient
from quantpilot.exchange.bybit import BybitClient
from quantpilot.market_data import binance_klines_to_frame, closed_bars, klines_to_frame
from quantpilot.metrics import report
from quantpilot.strategy import generate_signal


@st.cache_data(ttl=60)
def load_bars(exchange: str, env_file: str):
    settings = Settings.from_env(env_file)
    client = BinanceFuturesClient(settings) if exchange == "binance" else BybitClient(settings)
    rows = client.get_klines(limit=200)
    frame = binance_klines_to_frame(rows) if exchange == "binance" else klines_to_frame(rows)
    return closed_bars(frame)

def main() -> None:
    st.set_page_config(page_title="QuantPilot", layout="wide")
    st.title("QuantPilot Research Dashboard")
    st.caption("Read-only research dashboard. No order controls are exposed.")
    settings = Settings.from_env(".env")
    st.sidebar.write(f"Exchange: {settings.exchange}")
    st.sidebar.write(f"Symbol: {settings.symbol}")
    testnet = settings.testnet if settings.exchange == "bybit" else settings.binance_testnet
    st.sidebar.write(f"Testnet: {testnet}")
    try:
        bars = load_bars(settings.exchange, ".env")
    except Exception as exc:  # noqa: BLE001
        st.error(f"Market data request failed: {exc}")
        st.stop()
    if bars.empty:
        st.warning("No closed bars were returned.")
        st.stop()
    result = run_backtest(bars)
    stats = report(result)
    signal = generate_signal(bars)
    cols = st.columns(5)
    cols[0].metric("Last close", f"{bars.iloc[-1]['close']:.2f}")
    cols[1].metric("Signal", signal)
    cols[2].metric("Return", f"{stats['total_return']:.2%}")
    cols[3].metric("Max drawdown", f"{stats['max_drawdown']:.2%}")
    cols[4].metric("Trades", int(stats["trades"]))
    st.subheader("Price")
    st.line_chart(bars.set_index("timestamp")["close"])
    st.subheader("Backtest equity")
    if not result.equity_curve.empty:
        st.line_chart(result.equity_curve)
    else:
        st.info("No trades were generated by the current sample.")

if __name__ == "__main__":
    main()

